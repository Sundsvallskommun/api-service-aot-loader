-- The status table, the runs with their report rows and the exception list (sections 7.1.1 and 8).
-- No names or numbers of permit holders or other persons are stored here (K6).

-- The target environment the database belongs to. The status table only holds for the environment it was written
-- against, so a run against another environment is refused.
CREATE TABLE migration_target (
    id                     INT                      NOT NULL,
    support_management_url VARCHAR(500)             NOT NULL,
    created                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_migration_target PRIMARY KEY (id)
);

CREATE TABLE migration_run (
    id              VARCHAR(36)              NOT NULL,
    municipality_id VARCHAR(10)              NOT NULL,
    dry_run         BOOLEAN                  NOT NULL,
    sources         VARCHAR(50)              NOT NULL,
    kinds           VARCHAR(50)              NOT NULL,
    item_key        VARCHAR(100),
    item_limit      INT,
    status          VARCHAR(20)              NOT NULL,
    message         VARCHAR(4000),
    started         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished        TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_migration_run PRIMARY KEY (id)
);

CREATE TABLE migration_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source          VARCHAR(10)              NOT NULL,
    kind            VARCHAR(20)              NOT NULL,
    source_id       VARCHAR(50)              NOT NULL,
    errand_type     VARCHAR(50),
    status          VARCHAR(30)              NOT NULL,
    failed_step     VARCHAR(30),
    reason          VARCHAR(4000),
    place_name      VARCHAR(255),
    place_number    VARCHAR(20),
    municipality_id VARCHAR(4),
    errand_id       VARCHAR(36),
    errand_number   VARCHAR(50),
    asset_id        VARCHAR(36),
    party_assets_id VARCHAR(36),
    relation_id     VARCHAR(36),
    last_run_id     VARCHAR(36),
    created         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modified        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_migration_item PRIMARY KEY (id),
    CONSTRAINT uq_migration_item_key UNIQUE (source, kind, source_id)
);

CREATE INDEX ix_migration_item_status ON migration_item (status);

CREATE TABLE run_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id        VARCHAR(36)              NOT NULL,
    source        VARCHAR(10)              NOT NULL,
    kind          VARCHAR(20)              NOT NULL,
    source_id     VARCHAR(50)              NOT NULL,
    outcome       VARCHAR(20)              NOT NULL,
    rules         VARCHAR(255),
    detail        VARCHAR(4000),
    place_name    VARCHAR(255),
    place_number  VARCHAR(20),
    errand_number VARCHAR(50),
    created       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_run_item PRIMARY KEY (id),
    CONSTRAINT fk_run_item_run FOREIGN KEY (run_id) REFERENCES migration_run (id)
);

CREATE INDEX ix_run_item_run ON run_item (run_id);

CREATE TABLE review_exception (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source     VARCHAR(10)              NOT NULL,
    kind       VARCHAR(20)              NOT NULL,
    source_id  VARCHAR(50)              NOT NULL,
    outcome    VARCHAR(30)              NOT NULL,
    decided_by VARCHAR(100)             NOT NULL,
    decided_at DATE                     NOT NULL,
    comment    VARCHAR(1000),
    created    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_review_exception PRIMARY KEY (id),
    CONSTRAINT uq_review_exception_key UNIQUE (source, kind, source_id)
);
